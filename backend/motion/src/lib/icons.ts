import {
  Apple,
  Bike,
  Bird,
  Building2,
  Bus,
  Car,
  Cat,
  Circle,
  Coins,
  Dog,
  Droplet,
  Egg,
  Fish,
  Flame,
  Footprints,
  Globe,
  Heart,
  House,
  Mountain,
  Plane,
  Rabbit,
  Rocket,
  Ship,
  Smartphone,
  Sun,
  TrainFront,
  TreePine,
  Truck,
  User,
  Weight,
  type LucideIcon,
} from "lucide-react";

// Iconos que puede pedir el planificador (campo `icon`). Las claves tienen
// que coincidir con "icons" de catalog.json, que es lo que lee el backend.
export const ICONS: Record<string, LucideIcon> = {
  apple: Apple,
  bike: Bike,
  bird: Bird,
  building: Building2,
  bus: Bus,
  car: Car,
  cat: Cat,
  coin: Coins,
  dog: Dog,
  drop: Droplet,
  egg: Egg,
  fish: Fish,
  fire: Flame,
  footprint: Footprints,
  globe: Globe,
  heart: Heart,
  house: House,
  mountain: Mountain,
  person: User,
  plane: Plane,
  rabbit: Rabbit,
  rocket: Rocket,
  ship: Ship,
  phone: Smartphone,
  sun: Sun,
  train: TrainFront,
  tree: TreePine,
  truck: Truck,
  weight: Weight,
};

export function iconFor(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || Circle;
}
